"""Run real collective compilation in bounded, independent MPI jobs."""
import base64
import inspect
import sys
import textwrap
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _helpers import make_environment, read_json, run_command, write_text
from F00_candidate import materialize_candidate
from F03_helpers import require_success


def collective_observation(directory, root_source, other_source, check, *, root_only=False):
    directory.mkdir(parents=True)
    candidate = materialize_candidate(directory)
    # Supply the real upstream dependency offline, including its license and
    # metadata. Importing this pure-Python wheel needs no runtime installation.
    dependency = directory / 'tblib-3.2.2-py3-none-any.whl'
    dependency.write_bytes(base64.b64decode(_TBLIB_WHEEL_BASE64, validate=True))
    write_text(directory, 'root_input.py', root_source)
    write_text(directory, 'other_input.py', other_source)
    driver = write_text(directory, 'collective_driver.py',
        'import sys\nimport json\nfrom pathlib import Path\n'
        + f'sys.path.insert(0, {str(candidate)!r})\n'
        + f'sys.path.insert(0, {str(dependency)!r})\n'
        + 'from mpi4py import MPI\nfrom zelvori import ezelvori\n'
        + f'sys.path.insert(0, {str(Path(__file__).resolve().parent)!r})\n'
        + 'from F00_candidate import _checked\nezelvori = _checked(ezelvori)\n'
        + 'import root_input\nimport other_input\n'
        + textwrap.dedent(inspect.getsource(check))
        + '\ncomm = MPI.COMM_WORLD\nassert comm.size == 3\n'
        + "for language in ('c', 'fortran'):\n"
        + f'    check(comm, ezelvori, root_input, other_input, language, {root_only!r})\n'
        + 'comm.Barrier()\n'
        + 'Path(f"completed_{comm.rank}.json").write_text(json.dumps(comm.rank))\n')
    result = run_command(
        # mpi4py's runner aborts the job on an unhandled assertion instead of
        # leaving surviving ranks blocked in another collective or finalizing.
        ['mpiexec', '--oversubscribe', '-n', '3', sys.executable, '-m', 'mpi4py', driver],
        cwd=directory, env=make_environment(), timeout=480,
    )
    require_success(result)
    # The driver writes these only after consuming every product result. A
    # premature successful interpreter exit must not masquerade as a pass.
    for rank in range(3):
        assert read_json(directory / f'completed_{rank}.json') == rank
    return result


