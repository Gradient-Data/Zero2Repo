"""Source fixtures and explicit public observations for suite construction."""
import ast
from velun.api import TestSuite
from _helpers import call_public, run_module, read_xml, write_file


def syntax_errors(model):
    errors = []
    for node in ast.walk(model):
        if node.errors:
            errors.append((node.lineno, tuple(node.errors)))
        for token in getattr(node, "tokens", ()):
            if token.error:
                errors.append((token.lineno, (token.error,)))
    return errors


def execute_suite(suite):
    return call_public(suite.run, output=None, log=None, report=None,
                       console="none").value.suite


def execute_source(path, directory, *options):
    output = directory / "result.xml"
    process = run_module("velun", ["--output", str(output), "--log", "NONE",
                         "--report", "NONE", *options, str(path)])
    return process, read_xml(output).getroot()


def leaf_suites(suite):
    return ([suite] if suite.tests else []) + [leaf for child in suite.suites
                                               for leaf in leaf_suites(child)]


def native_case(name="Witness"):
    return f"*** Test Cases ***\n{name}\n    No Operation\n"


